#!/usr/bin/env python3
"""All SensorPulse reporting in one entry point (stdlib only).

  report.py bench RUN_DIR            report.html for one benchmark run
  report.py ramp RUN_DIR             ramp-report.html for one ramp run
  report.py auth BASE_DIR JWT_DIR    auth-overhead.html: cost of JWT (two benchmark runs)
  report.py all [--bench DIR] [--ramp DIR ...] [--base DIR --jwt DIR]
                                     results/report.html: scorecard + benchmark + ramps + auth + run list
  report.py index                    results/index.html: catalogue of every run
  report.py refresh                  index + combined report (runs automatically after bench/ramp)

For backwards compatibility `report.py RUN_DIR` is treated as `report.py bench RUN_DIR`."""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from reporting import auth, bench, combined, ramp, runs  # noqa: E402
from reporting.common import RESULTS, esc, name_of, nav, page, write  # noqa: E402


def standalone(title, subtitle, meta, links, body, footer):
    return page(title, f"<header><h1>{esc(title)}</h1><p>{esc(subtitle)}</p><div class='meta'>{meta}</div></header>{nav(links)}{body}<footer>{esc(footer)}</footer>")


def cmd_bench(run_dir):
    run = bench.load(run_dir)
    links, body, _ = bench.render(run)
    subtitle = " vs ".join(name_of(s) for s in run["ran"]) + " on identical PostgreSQL data, API contract and Docker limits."
    out = os.path.join(run_dir, "report.html")
    write(out, standalone("SensorPulse benchmark report", subtitle, bench.meta_html(run), links, body,
                          f"Generated by scripts/report.py · {len(run['ran'])} stack(s) · {len(run['cells'])} measured run(s)"))
    return out


def cmd_ramp(run_dir):
    run = ramp.load(run_dir)
    links, body, _ = ramp.render(run)
    out = os.path.join(run_dir, "ramp-report.html")
    write(out, standalone("SensorPulse ramp report",
                          "Offered load climbs step by step. Each step holds a fixed request rate (open model), so latency and errors show where each stack saturates.",
                          ramp.meta_html(run), links, body, "Generated by scripts/report.py"))
    return out


def cmd_auth(base, jwt):
    rows = auth.overhead(base, jwt)
    for r in rows:
        print(f"{r['workload']:8} {r['stack']:8} {r['base']['rps']:>9,.0f} -> {r['jwt']['rps']:>9,.0f}  {r['change']:+6.1f}%")
    _, body, _ = auth.render({}, (base, jwt))
    out = os.path.join(jwt, "auth-overhead.html")
    write(out, page("JWT Auth Overhead", body))
    return out


def cmd_index(root=RESULTS):
    body = ("<h1>SensorPulse results</h1><p class='sub'>Every run, newest first. <a class='open' href='report.html'>Open the combined report</a>. "
            "Rebuilt after every run (<code>python3 scripts/report.py refresh</code>).</p>" + runs.catalogue(root))
    return write(os.path.join(root, "index.html"), page("SensorPulse Results", body))


def cmd_refresh(root=RESULTS):
    """Never lets a reporting problem fail the benchmark that just finished."""
    paths = []
    for fn in (cmd_index, combined.write_combined):
        try:
            paths.append(fn(root))
        except Exception as e:  # noqa: BLE001
            print(f"warning: {fn.__name__} failed: {e!r}", file=sys.stderr)
    return paths


def main(argv):
    if argv and argv[0] not in ("bench", "ramp", "auth", "all", "index", "refresh", "-h", "--help") and os.path.isdir(argv[0]):
        argv = ["bench"] + argv   # legacy: report.py RUN_DIR
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("bench").add_argument("run_dir")
    sub.add_parser("ramp").add_argument("run_dir")
    a = sub.add_parser("auth")
    a.add_argument("base")
    a.add_argument("jwt")
    al = sub.add_parser("all")
    al.add_argument("--bench")
    al.add_argument("--ramp", action="append")
    al.add_argument("--base")
    al.add_argument("--jwt")
    sub.add_parser("index")
    sub.add_parser("refresh")
    args = ap.parse_args(argv)

    if args.cmd == "bench":
        print(cmd_bench(args.run_dir.rstrip("/")))
        cmd_refresh()
    elif args.cmd == "ramp":
        print(cmd_ramp(args.run_dir.rstrip("/")))
        cmd_refresh()
    elif args.cmd == "auth":
        print(cmd_auth(args.base.rstrip("/"), args.jwt.rstrip("/")))
    elif args.cmd == "all":
        pair = (args.base, args.jwt) if args.base and args.jwt else None
        print(combined.write_combined(bench_dir=args.bench, ramp_dirs=args.ramp, pair=pair))
    elif args.cmd == "index":
        print(cmd_index())
    else:
        for p in cmd_refresh():
            print(p)


if __name__ == "__main__":
    main(sys.argv[1:])
